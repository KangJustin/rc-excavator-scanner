"""FreeCAD macro text for each shape. The macro is a standalone, human-editable script: run it in
FreeCAD (Macro > Macros... > Execute) or headless (`freecadcmd macro.FCMacro`)."""
from __future__ import annotations

TOP = r'''# -*- coding: utf-8 -*-
"""
@TITLE@

Generated by `python -m cad` from the 3D scan @SOURCE@.
Detected shape: @FIT@.
@HOWTO@
Run: FreeCAD > Macro > Macros... > Execute. Tested on FreeCAD 1.1 (AttachmentSupport, falling back to
Support for 0.21).
"""
import json
import math

import FreeCAD as App
import Part
import Sketcher
from FreeCAD import Vector

# =====================================================================================
#  EDIT THESE, then run the macro again
# =====================================================================================
DOC_NAME = "@DOC@"
@PARAMS@
SCALE_CONFIRMED = @SCALE_CONFIRMED@  # False => the document is tagged "(UNSCALED)": sizes are not real mm
COLOR_RGB = @COLOR@  # (r, g, b) 0-255: the object's dominant colour as seen in the scan, or None
EXPORT_STL_PATH = ""   # optional: write an STL
EXPORT_STEP_PATH = ""  # optional: write a STEP file
SAVE_FCSTD_PATH = ""   # optional: save the editable FreeCAD document
REPORT_JSON_PATH = ""  # optional: write volume / bounding box / validity as JSON

# =====================================================================================
#  Build (you shouldn't need to edit below this line)
# =====================================================================================
C = Sketcher.Constraint
TOLERANCE = @TOLERANCE@  # allowed relative volume error in the self-check


def _spreadsheet(doc, cells):
    """Parameters live in a spreadsheet so they can be edited without touching code."""
    sheet = doc.addObject("Spreadsheet::Sheet", "Params")
    for i, (alias, value) in enumerate(cells, 1):
        sheet.set("A%d" % i, alias)
        sheet.set("B%d" % i, "=%r mm" % float(value))
        sheet.setAlias("B%d" % i, alias)
    doc.recompute()
    return sheet


def _sketch(body, plane_role, name="ProfileSketch"):
    plane = next(o for o in body.Origin.OriginFeatures if o.Role == plane_role)
    sk = body.newObject("Sketcher::SketchObject", name)
    if hasattr(sk, "AttachmentSupport"):  # FreeCAD 1.0+
        sk.AttachmentSupport = [(plane, "")]
    else:  # FreeCAD 0.21
        sk.Support = (plane, [""])
    sk.MapMode = "FlatFace"
    return sk

@BUILD@

def build():
    doc = App.newDocument(DOC_NAME)
    doc.Label = DOC_NAME + ("" if SCALE_CONFIRMED else " (UNSCALED)")
    obj, sketch, expected, parametric = build_shape(doc)
    shape = obj.Shape
    if not shape.isValid() or abs(shape.Volume - expected) > TOLERANCE * expected:
        raise RuntimeError("Build check failed: volume %.1f vs expected %.1f mm^3 (valid=%s)"
                           % (shape.Volume, expected, shape.isValid()))
    if App.GuiUp:
        try:
            import FreeCADGui
            gdoc = FreeCADGui.getDocument(doc.Name)
            gdoc.getObject(obj.Name).Visibility = True  # a document saved without GUI state opens hidden
            if sketch is not None:
                gdoc.getObject(sketch.Name).Visibility = False
            if COLOR_RGB is not None:
                for o in [obj] + [f for f in doc.Objects if f.TypeId.startswith("PartDesign::") and f is not obj]:
                    try:
                        gdoc.getObject(o.Name).ShapeColor = tuple(c / 255.0 for c in COLOR_RGB)
                    except Exception:
                        pass
            FreeCADGui.ActiveDocument.ActiveView.viewIsometric()
            FreeCADGui.SendMsgToActiveView("ViewFit")
        except Exception:
            pass
    bb = shape.BoundBox
    App.Console.PrintMessage("Built %s: %.1f x %.1f x %.1f mm, volume %.0f mm^3 (%.1f mL)\n"
                             % (DOC_NAME, bb.XLength, bb.YLength, bb.ZLength, shape.Volume, shape.Volume / 1000.0))
    if EXPORT_STL_PATH:
        import Mesh
        Mesh.export([obj], EXPORT_STL_PATH)
    if EXPORT_STEP_PATH:
        import Import
        Import.export([obj], EXPORT_STEP_PATH)
    if SAVE_FCSTD_PATH:
        doc.saveAs(SAVE_FCSTD_PATH)
    if REPORT_JSON_PATH:
        with open(REPORT_JSON_PATH, "w") as f:
            json.dump({"volume_mm3": shape.Volume, "valid": shape.isValid(), "faces": len(shape.Faces),
                       "bbox_mm": [bb.XLength, bb.YLength, bb.ZLength], "parametric": parametric,
                       "expected_volume_mm3": expected,
                       "features": [o.TypeId for o in doc.Objects if o.TypeId.startswith(("PartDesign::", "Sketcher::", "Spreadsheet::"))]}, f)
    return doc


build()
'''

SPHERE = r'''
def build_shape(doc):
    d = float(DIAMETER_MM)
    sheet = _spreadsheet(doc, [("Diameter", d)])
    sheet.set("A2", "Radius")
    sheet.set("B2", "=Diameter / 2")
    sheet.setAlias("B2", "Radius")
    doc.recompute()
    body = doc.addObject("PartDesign::Body", "Body")
    sk = _sketch(body, "XZ_Plane")  # sketch X = world X, sketch Y = world Z
    # Half-disc: a vertical line from the ground (0,0) up to (0,D), closed by a semicircle bulging to +X.
    line = sk.addGeometry(Part.LineSegment(Vector(0, 0, 0), Vector(0, d, 0)), False)
    arc = sk.addGeometry(Part.ArcOfCircle(Part.Circle(Vector(0, d / 2, 0), Vector(0, 0, 1), d / 2),
                                          -math.pi / 2, math.pi / 2), False)
    sk.addConstraint(C("Coincident", line, 1, -1, 1))  # start on the origin
    sk.addConstraint(C("Vertical", line))
    sk.addConstraint(C("Coincident", arc, 1, line, 1))
    sk.addConstraint(C("Coincident", arc, 2, line, 2))
    sk.addConstraint(C("PointOnObject", arc, 3, line))  # centre on the line => a true semicircle
    i = sk.addConstraint(C("Distance", line, d))
    sk.renameConstraint(i, "Diameter")
    sk.setExpression("Constraints.Diameter", "Params.Diameter")
    doc.recompute()
    rev = body.newObject("PartDesign::Revolution", "SphereRevolution")
    rev.Profile = sk
    rev.ReferenceAxis = (sk, ["V_Axis"])
    rev.Angle = 360.0
    doc.recompute()
    return body, sk, 4.0 / 3.0 * math.pi * (d / 2) ** 3, True
'''

CYLINDER = r'''
def build_shape(doc):
    d, h = float(DIAMETER_MM), float(HEIGHT_MM)
    _spreadsheet(doc, [("Diameter", d), ("Height", h)])
    body = doc.addObject("PartDesign::Body", "Body")
    sk = _sketch(body, "XY_Plane")
    circle = sk.addGeometry(Part.Circle(Vector(0, 0, 0), Vector(0, 0, 1), d / 2), False)
    sk.addConstraint(C("Coincident", circle, 3, -1, 1))  # centre on the origin
    i = sk.addConstraint(C("Diameter", circle, d))
    sk.renameConstraint(i, "Diameter")
    sk.setExpression("Constraints.Diameter", "Params.Diameter")
    doc.recompute()
    pad = body.newObject("PartDesign::Pad", "Pad")
    pad.Profile = sk
    pad.Length = h
    pad.setExpression("Length", "Params.Height")
    doc.recompute()
    return body, sk, math.pi * (d / 2) ** 2 * h, True
'''

BOX = r'''
def build_shape(doc):
    L, W, H = float(LENGTH_MM), float(WIDTH_MM), float(HEIGHT_MM)
    _spreadsheet(doc, [("Length", L), ("Width", W), ("Height", H)])
    body = doc.addObject("PartDesign::Body", "Body")
    sk = _sketch(body, "XY_Plane")
    a, b = L / 2, W / 2
    P = [Vector(-a, -b, 0), Vector(a, -b, 0), Vector(a, b, 0), Vector(-a, b, 0)]
    for k in range(4):
        sk.addGeometry(Part.LineSegment(P[k], P[(k + 1) % 4]), False)
    for k in range(4):
        sk.addConstraint(C("Coincident", k, 2, (k + 1) % 4, 1))
    sk.addConstraint(C("Horizontal", 0)); sk.addConstraint(C("Horizontal", 2))
    sk.addConstraint(C("Vertical", 1)); sk.addConstraint(C("Vertical", 3))
    sk.addConstraint(C("Symmetric", 0, 1, 2, 1, -1, 1))  # opposite corners symmetric about the origin
    i = sk.addConstraint(C("Distance", 0, L)); sk.renameConstraint(i, "Length")
    j = sk.addConstraint(C("Distance", 1, W)); sk.renameConstraint(j, "Width")
    sk.setExpression("Constraints.Length", "Params.Length")
    sk.setExpression("Constraints.Width", "Params.Width")
    doc.recompute()
    pad = body.newObject("PartDesign::Pad", "Pad")
    pad.Profile = sk
    pad.Length = H
    pad.setExpression("Length", "Params.Height")
    doc.recompute()
    return body, sk, L * W * H, True
'''

SOLID = r'''
def build_shape(doc):
    """NOT parametric: the scan's own triangles converted to a B-rep solid (one planar face per triangle)."""
    import Mesh
    mesh = Mesh.Mesh(MESH_PATH)
    shape = Part.Shape()
    shape.makeShapeFromMesh(mesh.Topology, TOLERANCE_MM)
    solid = Part.makeSolid(Part.makeShell(shape.Faces))
    if solid.Volume < 0:
        solid.reverse()
    obj = doc.addObject("Part::Feature", "ScannedSolid")
    obj.Shape = solid
    doc.recompute()
    return obj, None, EXPECTED_VOLUME_MM3, False
'''

HOWTO = {
    "sphere": "Feature tree: Params (spreadsheet) > Body > ProfileSketch > SphereRevolution.\n"
              "Change Params.Diameter (cell B1) and recompute (Ctrl+R) to resize.",
    "cylinder": "Feature tree: Params (spreadsheet) > Body > ProfileSketch > Pad.\n"
                "Change Params.Diameter / Params.Height and recompute (Ctrl+R) to resize.",
    "box": "Feature tree: Params (spreadsheet) > Body > ProfileSketch > Pad.\n"
           "Change Params.Length / Width / Height and recompute (Ctrl+R) to resize.",
    "solid": "NOT PARAMETRIC: this is the scan's own surface as a solid (exact, but you cannot edit dimensions).\n"
             "It is what to fall back on for irregular objects that no sphere/cylinder/box describes.",
}
BUILDERS = {"sphere": SPHERE, "cylinder": CYLINDER, "box": BOX, "solid": SOLID}
TOLERANCES = {"sphere": 0.005, "cylinder": 0.005, "box": 0.005, "solid": 0.02}


def macro_source(plan: dict, doc_name: str, source: str, scale_confirmed: bool,
                 mesh_path: str | None = None, expected_volume: float | None = None,
                 color: tuple | None = None) -> str:
    shape = plan["shape"]
    lines = [f"{k} = {v!r}" for k, v in plan["params"].items()]
    if shape == "solid":
        lines += [f"MESH_PATH = {str(mesh_path)!r}", "TOLERANCE_MM = 0.05  # vertex-welding tolerance",
                  f"EXPECTED_VOLUME_MM3 = {float(expected_volume)!r}  # volume of the source mesh, for the self-check"]
    text = TOP.replace("@BUILD@", BUILDERS[shape])
    for key, val in {
        "@TITLE@": f"Parametric {shape} from a 3D scan" if shape != "solid" else "Solid from a 3D scan (not parametric)",
        "@SOURCE@": source, "@FIT@": plan["fit_note"], "@HOWTO@": HOWTO[shape], "@DOC@": doc_name,
        "@PARAMS@": "\n".join(lines), "@SCALE_CONFIRMED@": str(bool(scale_confirmed)),
        "@TOLERANCE@": repr(TOLERANCES[shape]), "@COLOR@": repr(tuple(color) if color else None),
    }.items():
        text = text.replace(key, val)
    return text
